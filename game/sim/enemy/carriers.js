/* ============================================================
   НОСИТЕЛИ РАКЕТ И ЛОЖНАЯ АКТИВНОСТЬ
   ------------------------------------------------------------
   Тяжёлые удары готовятся часами, и разведка ПВО видит подготовку:
   шифрованный обмен, подвеску ракет, взлёт бомбардировщиков, выход
   кораблей в море, выдвижение пусковых. carrierIntel() расписывает
   эту цепочку сводок для пакета.
   Ложная активность (feint) — та же цепочка без пусков: сторона налёта
   поднимает носители, чтобы ПВО включила радары, объявила тревогу и
   сожгла ресурс. Позже разведка может заметить, что носители вернулись.
   Вымышленные носители:
     «Кондор-95»  — турбовинтовой стратегический бомбардировщик (до 8 КР «Альбатрос»)
     «Гроза-160»  — сверхзвуковой стратегический (до 12 КР)
     МРК «Шквал» — малый ракетный корабль (8 КР «Кречет-М»)
     ПЛ «Палтус» — подводная лодка (4 КР «Кречет-М»)
     «Сокол-31»   — перехватчик-носитель «Гарпии»
   ============================================================ */

const FEINT_KINDS = {
  bomb: { n: 'Стратегическая авиация', k: 'albatros', zid: 'bomb', cap: 1, d: '«Кондоры» взлетают и идут к рубежу пусков, но не пускают' },
  sea: { n: 'Носители в море', k: 'krechet', zid: 'sea', cap: 1, d: 'МРК «Шквал» выходят в море и маневрируют в районе пусков' },
  molot: { n: 'Выдвижение ОТРК', k: 'molot', zid: null, cap: 2, d: 'пусковые «Молота» выходят на позиции и работают в эфире' },
  garpia: { n: 'Взлёт носителей «Гарпии»', k: 'garpia', zid: 'mig', cap: 1, d: '«Соколы-31» поднимаются и ходят у рубежа' },
  drones: { n: 'Активность пусковых БпЛА', k: 'jalo', zid: null, cap: 2, d: 'расчёты дронов разворачиваются и шумят в эфире' }
};

const LONG_CH = ['«Сирин»', '«Пурга»', '«Вьюга»', '«Гранит»', '«Тайфун»'];
const FLEET_CH = ['«Бриз»', '«Шторм»', '«Прибой»', '«Скала»'];

/**
 * сводки о подготовке и пуске тяжёлого пакета.
 * k — средство, z — район, t — время первого пуска, n — сколько, arrive — подлёт,
 * feint — ложная активность (пусков не будет)
 */
function carrierIntel(k, z, t, n, arrive, feint) {
  const fl = Math.max(1, Math.round(((arrive || t) - t) / 60));
  if (k === 'albatros') {
    const kondor = Math.max(1, Math.ceil(n / 8)), groza = n > 16 ? 1 : 0;
    const planes = `${kondor} «Кондор-95»` + (groza ? ` и «Гроза-160»` : '');
    intelAt(t - R(5.5, 7) * 3600, `Радиоперехват: шифрованный обмен на каналах дальней авиации ${pick(LONG_CH)}. Объём выше обычного.`, 'C-3', '', .7);
    intelAt(t - R(4, 5) * 3600, `Партнёры: на ${AIRBASE_E} под бомбардировщики подвешивают ракеты.`, 'B-2', '', .55);
    intelAt(t - R(2.6, 3.4) * 3600, `Взлёт: ${planes}, ${AIRBASE_E}. Курс — к рубежу пусков.`, 'A-1', 'w', .95);
    intelAt(t - R(40, 70) * 60, `${kondor > 1 || groza ? 'Бомбардировщики выходят' : '«Кондор-95» выходит'} к рубежу «Восход». Пуски возможны в течение часа.`, 'B-2', 'w', .85);
    if (!feint) intelAt(t + R(60, 200), `ПУСКИ КР «Альбатрос» с рубежа «Восход»: ~${approx(n)}. Подлёт ≈ ${fl} мин.`, 'A-1', 'crit', .95);
    else intelAt(t + R(40, 120) * 60, `Бомбардировщики развернулись от рубежа и возвращаются на ${AIRBASE_E}. Пусков не зафиксировано.`, 'B-2', '', .6);
  }
  else if (k === 'krechet') {
    const ships = Math.max(1, Math.ceil(n / 8)), sub = n >= 6 && chance(.5);
    intelAt(t - R(6, 7.5) * 3600, `Радиоперехват: активность на каналах флота ${pick(FLEET_CH)}, шифрованный трафик.`, 'C-3', '', .6);
    intelAt(t - R(3.5, 5) * 3600, `В море вышли носители крылатых ракет: ${ships} МРК «Шквал»${sub ? ', предположительно ПЛ «Палтус»' : ''}. Залп — до ${n + RI(0, 4)} ед.`, 'B-2', 'w', .9);
    intelAt(t - R(30, 60) * 60, `Носители маневрируют в районе пусков (${z.n}).`, 'C-2', '', .6);
    if (!feint) intelAt(t + R(30, 120), `ПУСКИ КР «Кречет-М» из акватории (${z.n}): ~${approx(n)}. Подлёт ≈ ${fl} мин.`, 'A-2', 'crit', .92);
    else intelAt(t + R(40, 120) * 60, `Носители уходят из района пусков в базу. Пусков не было.`, 'C-2', '', .5);
  }
  else if (k === 'molot') {
    intelAt(t - R(40, 80) * 60, `Пограничники: колонна тяжёлой техники выдвигается в районе ${z.n}. Возможно, пусковые ОТРК.`, 'C-3', '', .5);
    intelAt(t - R(10, 30) * 60, `Радиоперехват: активность расчётов ОТРК «Молот», район ${z.n}.`, 'C-2', 'w', .6);
    if (!feint) intelAt(t + R(3, 10), `ПУСК БАЛЛИСТИКИ, район ${z.n}! Ракет: ${n}. Подлёт ≈ ${fl} мин.`, 'A-1', 'crit', .97);
    else intelAt(t + R(30, 90) * 60, `Пусковые ОТРК в районе ${z.n} свернулись и ушли. Пусков не было.`, 'C-3', '', .4);
  }
  else if (k === 'garpia') {
    intelAt(t - R(25, 45) * 60, `Взлёт ${n > 1 ? 'пары' : 'одного'} «Сокол-31» — носители аэробаллистических ракет «Гарпия».`, 'A-2', 'w', .85);
    if (!feint) intelAt(t + R(3, 8), `ПУСК «ГАРПИИ»! Подлёт ≈ ${fl} мин.`, 'A-1', 'crit', .95);
    else intelAt(t + R(20, 60) * 60, '«Соколы-31» вернулись на аэродром. Пусков не было.', 'B-3', '', .5);
  }
  else if (k === 'jalo') {
    intelAt(t - R(10, 30) * 60, `Радиоперехват: пусковые расчёты БпЛА в районе ${z.n} выходят на связь.`, 'C-3', '', .6);
    intelAt(t + R(120, 600), `Мониторинг: пуски ударных БпЛА из района ${z.n}, ориентировочно ${approx(n)}.`, 'B-2', 'w', feint ? .7 : .85);
  }
}

/** ложная активность: команда стороны налёта */
function launchFeint(p) {
  const fail = error => { toast(error, 'i'); return { ok: false, error } };
  if (G.phase !== 'prep' && G.phase !== 'night') return fail('Ложную активность готовят днём в план или ночью');
  const F = p && FEINT_KINDS[p.kind];
  if (!F) return fail('Неизвестный вид ложной активности');
  E.feintUsed = E.feintUsed || {};
  if ((E.feintUsed[p.kind] || 0) >= FEINTS[p.kind].cap) return fail(`На эту ночь «${F.n}» уже использована`);
  const zones = zonesFor(F.k);
  const zone = zones.find(z => z.id === (p.zid || F.zid)) || zones[0];
  const delay = STRIKE_DELAYS.includes(+p.delay) ? +p.delay : 0;
  /* время «пуска», который так и не случится: те же сроки подготовки, что и у настоящего */
  const t = Math.max(earliestLaunch(F.k, zone.id, delay), (G.phase === 'night' ? G.t : 0) + 600);
  if (t > NIGHT_LEN - 1800) return fail('До рассвета ложная активность не успеет развернуться');
  const n = F.k === 'albatros' ? RI(12, 24) : F.k === 'krechet' ? RI(8, 16) : F.k === 'molot' ? RI(2, 4) : F.k === 'garpia' ? RI(1, 2) : RI(15, 30);
  E.feintUsed[p.kind] = (E.feintUsed[p.kind] || 0) + 1;
  const id = (E.fid = (E.fid || 0) + 1);
  (E.feints = E.feints || []).push({ id, kind: p.kind, t, zone: { id: zone.id, n: zone.n } });
  carrierIntel(F.k, zone, t, n, t + 3600, true);
  if (MODE.onFeint) MODE.onFeint(t);
  hq(`Ложная активность: ${F.n.toLowerCase()} — ${F.d}. «Пуск» около ${clock(t)}, но ракеты не уйдут.`, 'hq');
  return { ok: true, id, t };
}
