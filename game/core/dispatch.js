/* ============================================================
   ФАСАД РАДИООБМЕНА
   Движок (comms/units/threats/enemy) говорит с игроком через эти
   пять функций. Что именно произойдёт — решает активный режим:
   в обороне это живой эфир с запросами расчётов, в налёте —
   тишина (расчёты бота отвечают сами).
   ============================================================ */

/** расчёт говорит в эфир */
function say(u, txt, cls) { MODE.say(u, txt, cls) }
/** разведсводка, которая придёт в момент t */
function intelAt(t, txt, gr, cls, ch) { MODE.intelAt(t, txt, gr, cls, ch) }
/** «мысли» противника (для режима наблюдателя / журнала налёта) */
function mind(txt) { MODE.mind(txt) }
/** расчёт просит решения штаба */
function ask(u, text, opts, def, key) { MODE.ask(u, text, opts, def, key) }
/** ответ на запрос расчёта */
function answerReq(id, i) { MODE.answerReq(id, i) }
