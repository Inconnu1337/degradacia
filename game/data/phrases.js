/* последние выбранные варианты — чтобы не повторяться подряд */
const __phLast = {};

function phr(key, a, u) {
  const set = PH[key];
  if (!set) return '';
  let list = (set.all || []).slice();
  if (u) {
    const tr = set[u.crew.trait];
    if (tr) list = list.concat(tr, tr);
    if (set.tired && u.crew.fat > .6) list = list.concat(set.tired, set.tired);
  }
  if (set.bad && G.weather && G.weather.eo < .8) list = list.concat(set.bad);
  return pickFresh(key + (u ? u.id : ''), list)(a || {});
}

function pickFresh(key, list) {
  if (list.length < 2) return list[0];
  let f;
  do f = pick(list); while (f === __phLast[key]);
  __phLast[key] = f;
  return f;
}
