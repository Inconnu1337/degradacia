/* ============================================================
   ГЛИФЫ ДЛЯ МАЛОГО МАСШТАБА (когда силуэт был бы кашей)
   ============================================================ */
function roleGlyph(g, u, r) {
  const T = UT[u.k];
  const role = T.w ? (T.w.kind === 'gun' ? 'gun' : 'sam') : (T.radar ? 'radar' : T.ewr ? 'ew' : T.sup ? 'sup' : 'sens');
  g.lineWidth = Math.max(1, r * .22);
  if (role === 'sam') { P(g, [[0, -r], [r * .92, r * .7], [-r * .92, r * .7]]) }
  else if (role === 'gun') { P(g, [[-r * .8, -r * .8], [r * .8, -r * .8], [r * .8, r * .8], [-r * .8, r * .8]]) }
  else if (role === 'radar') { g.beginPath(); g.arc(0, 0, r * .85, 0, 7) }
  else if (role === 'ew') { P(g, [[0, -r], [r, 0], [0, r], [-r, 0]]) }
  else if (role === 'sup') { P(g, [[-r * .8, -r * .5], [r * .8, -r * .5], [r * .8, r * .5], [-r * .8, r * .5]]) }
  else { g.beginPath(); g.arc(0, 0, r * .6, 0, 7) }
  return role;
}
