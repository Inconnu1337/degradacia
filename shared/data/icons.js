/** ширина и высота сетки иконки */
const iconBox = () => ({ w: ICON_W, h: ICON_H });

/**
 * иконка как SVG-группа (для газеты): тон → цвет по палитре pal,
 * тон 'b' можно залить штриховкой (hatch — id паттерна)
 */
function iconSVG(key, x, y, scale, pal, flip) {
  const L = ICONS[key];
  if (!L) return '';
  const tf = flip ? `translate(${_n(x + ICON_W * scale)} ${_n(y)}) scale(${-scale} ${scale})` : `translate(${_n(x)} ${_n(y)}) scale(${scale})`;
  return `<g transform="${tf}">${L.map(([t, d]) => `<path d="${d}" fill="${pal[t] || pal.b}"${pal.stroke && (t === 'b' || t === 's') ? ` stroke="${pal.stroke}" stroke-width="${pal.sw || .8}"` : ''}/>`).join('')}</g>`;
}
